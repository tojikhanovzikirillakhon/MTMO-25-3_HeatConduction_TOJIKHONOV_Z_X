// Простая модель теплопроводности на p5.js.
// Температура условная: 0 — холодная точка, 1 — максимальный нагрев.

// Количество точек по горизонтали и вертикали.
let cols = 60, rows = 36;
// Два двумерных массива: текущее состояние и результат следующего шага.
// Обращение temperature[y][x] означает температуру точки в строке y, столбце x.
let temperature = [], next = [];
// metal — список металлов, power — ползунок нагрева, cell — расстояние между точками.
let metal, power, cell;

// p5.js вызывает setup один раз при запуске программы.
function setup() {
  // Создаём заголовок и короткую инструкцию на странице.
  createElement('h2', 'Теплопроводность');
  createP('Зажми мышь на пластине, чтобы нагреть её.');

  // Создаём общий блок для элементов управления.
  let controls = createDiv();
  controls.style('display', 'flex'); // Располагаем элементы в строку.
  controls.style('align-items', 'center'); // Выравниваем по центру строки.
  controls.style('flex-wrap', 'wrap'); // На узком экране разрешаем перенос.
  controls.style('gap', '10px'); // Оставляем промежутки между элементами.

  // parent помещает подпись и список внутрь блока controls.
  createSpan('Металл:').parent(controls);
  metal = createSelect().parent(controls);
  // Первый аргумент option — надпись, второй — значение для проверки в коде.
  metal.option('Медь', 'copper');
  metal.option('Алюминий', 'aluminum');
  metal.option('Нержавеющая сталь', 'steel');
  // При смене металла вызываем resetPlate, чтобы начать опыт заново.
  metal.changed(resetPlate);

  // Создаём подпись и ползунок: минимум 1, максимум 10, начало 5, шаг 1.
  createSpan('Нагрев:').parent(controls);
  power = createSlider(1, 10, 5, 1).parent(controls);
  power.style('width', '100px'); // Задаём длину ползунка.
  // При нажатии кнопки вызываем ту же функцию сброса.
  createButton('Сброс').parent(controls).mousePressed(resetPlate);

  // Ширина поля не больше 720 пикселей и помещается в окно с отступами.
  let w = min(720, windowWidth - 32);
  let canvasBox = createDiv(); // Блок для поля под элементами управления.
  // Высота пропорциональна числу строк: шаг между точками одинаков по обеим осям.
  createCanvas(w, w * rows / cols).parent(canvasBox);
  cell = width / cols; // width — ширина холста, которую предоставляет p5.js.
  frameRate(60); // Просим p5.js рисовать до 60 кадров в секунду.
  resetPlate(); // Заполняем массивы нулями перед первым кадром.

  // Цветная полоска показывает последовательность цветов при нагревании.
  let scale = createDiv();
  scale.style('width', w + 'px'); // Ширина совпадает с шириной поля.
  scale.style('height', '8px'); // Высота полоски в пикселях.
  scale.style('background', 'linear-gradient(to right, blue, red, yellow, white)');
  createP('Синий — холодно, красный — горячо, белый — сильный нагрев.');
}

// Эта функция делает все точки холодными: используется при запуске и сбросе.
function resetPlate() {
  // Внешний цикл перебирает строки сетки.
  for (let y = 0; y < rows; y++) {
    temperature[y] = []; // Создаём строку текущего состояния.
    next[y] = []; // Создаём такую же строку следующего состояния.
    // Внутренний цикл перебирает столбцы в выбранной строке.
    for (let x = 0; x < cols; x++) {
      temperature[y][x] = 0; // Начальный нагрев равен нулю.
      next[y][x] = 0; // Второй массив тоже очищаем.
    }
  }
}

// p5.js вызывает draw снова и снова: здесь выполняются расчёт и рисование.
function draw() {
  background(0); // Очищаем предыдущий кадр чёрным цветом.
  // k — условный коэффициент обмена теплом. По умолчанию выбрана медь.
  let k = 0.22;
  // Проверяем выбранный металл и при необходимости меняем коэффициент.
  if (metal.value() === 'aluminum') k = 0.186;
  if (metal.value() === 'steel') k = 0.007;

  // Четыре шага за кадр делают распространение тепла заметнее.
  for (let step = 0; step < 4; step++) {
    // Два вложенных цикла проходят по каждой точке пластины.
    for (let y = 0; y < rows; y++) {
      for (let x = 0; x < cols; x++) {
        let t = temperature[y][x]; // Старая температура текущей точки.
        // Берём температуры четырёх соседей.
        // max и min не позволяют выйти за границы массива.
        // На краю вместо отсутствующего соседа берём саму крайнюю точку.
        let left = temperature[y][max(0, x - 1)];
        let right = temperature[y][min(cols - 1, x + 1)];
        let up = temperature[max(0, y - 1)][x];
        let down = temperature[min(rows - 1, y + 1)][x];

        // Если соседи в среднем горячее, точка нагреется; если холоднее — остынет.
        // Разность суммы температур соседей и 4*t задаёт направление обмена.
        let value = t + k * (left + right + up + down - 4 * t);
        value *= 0.999; // Небольшая потеря тепла в окружающую среду.

        // Греем только при зажатой мыши, когда указатель находится внутри поля.
        // && означает, что все перечисленные условия должны выполняться вместе.
        if (mouseIsPressed && mouseX >= 0 && mouseX < width && mouseY >= 0 && mouseY < height) {
          // Переводим координаты мыши из пикселей в координаты сетки.
          // x+0.5 и y+0.5 — положение центра точки. dist вычисляет расстояние.
          let d = dist(x + 0.5, y + 0.5, mouseX / cell, mouseY / cell);
          // Источник действует в круге радиусом четыре шага сетки.
          // power.value() — сила нагрева; 1-d/4 ослабляет его к краю круга.
          // Множитель 1-value замедляет нагрев при приближении температуры к 1.
          if (d < 4) value += (1 - value) * power.value() * 0.02 * (1 - d / 4);
        }
        // Ограничиваем температуру диапазоном 0...1 и записываем в другой массив.
        next[y][x] = constrain(value, 0, 1);
      }
    }
    // Меняем массивы местами после расчёта ВСЕХ точек.
    // Так соседи всегда берутся из одного старого состояния, а не из смеси шагов.
    let temp = temperature; // Временно сохраняем ссылку на старый массив.
    temperature = next; // Рассчитанный массив становится текущим.
    next = temp; // Старый массив используем для записи следующего шага.
  }

  noStroke(); // Рисуем точки без контуров.
  // Снова обходим сетку, теперь для рисования рассчитанного состояния.
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      // heatColor переводит температуру в цвет, fill задаёт цвет заливки.
      fill(heatColor(temperature[y][x]));
      // Переводим координаты сетки в пиксели и рисуем круг.
      // Диаметр меньше шага сетки, поэтому между точками остаются промежутки.
      circle((x + 0.5) * cell, (y + 0.5) * cell, cell * 0.55);
    }
  }
}

// Возвращаем цвет для температуры t в диапазоне 0...1.
// lerpColor смешивает два цвета: последний аргумент меняется от 0 до 1.
function heatColor(t) {
  // Нижняя половина шкалы: от синего к красному.
  if (t < 0.5) return lerpColor(color('blue'), color('red'), t / 0.5);
  // Следующий участок: от красного к жёлтому.
  if (t < 0.8) return lerpColor(color('red'), color('yellow'), (t - 0.5) / 0.3);
  // Самые горячие точки: от жёлтого к белому.
  return lerpColor(color('yellow'), color('white'), (t - 0.8) / 0.2);
}
